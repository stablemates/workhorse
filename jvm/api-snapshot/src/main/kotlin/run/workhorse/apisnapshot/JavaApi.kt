private const val JAVA_HEADER =
  """# Public Java API
#
# Generated by `pnpm java-api:generate` from the workhorse and workhorse-spring-boot-starter jars.
# ADR 0054 and ADR 0103 govern this surface: a removed or renamed public declaration or
# `workhorse.*` property and a narrowed signature are breaking, and an addition is not.
#
# Each artifact section lists every public and protected declaration of an exported package. A
# member line starts with the name of the class that declares it. Types are fully qualified, and
# `@Nullable` and `@NonNull` are the JSpecify type annotations. Parameter names are left out,
# because a Java caller cannot see them.
"""

/** The section of each artifact, then the `workhorse.*` properties of the starter. */
internal fun javaSnapshot(artifacts: List<Pair<String, Path>>, classpath: List<Path>): String {
  val urls = (artifacts.map { it.second } + classpath).distinct().map { it.toUri().toURL() }
  // The platform loader is the parent, so the reader's own dependencies, which include Jackson
  // and the Kotlin compiler, never stand in for a class of the artifacts.
  return URLClassLoader(urls.toTypedArray(), ClassLoader.getPlatformClassLoader()).use { loader ->
    val sections = mutableListOf<List<String>>()
    for ((artifact, jar) in artifacts) {
      sections += listOf("artifact $artifact")
      for (name in publicClassNames(jar)) {
        val type = Class.forName(name, false, loader)
        if (accessible(type)) sections += JavaClass(type).lines()
      }
      properties(jar, loader)?.let { sections += listOf("properties of $artifact") + it }
    }
    render(JAVA_HEADER, sections)
  }
}

/**
 * The binary names of the classes in the exported packages of a jar, sorted.
 *
 * A jar with a `module-info.class` exports the packages its descriptor exports to every module. A
 * jar without one is an automatic module, which exports every package.
 */
private fun publicClassNames(jar: Path): List<String> =
  JarFile(jar.toFile()).use { file ->
    val exported =
      file.getJarEntry("module-info.class")?.let { entry ->
        file.getInputStream(entry).use { input ->
          ModuleDescriptor.read(input)
            .exports()
            .filterNot { it.isQualified }
            .map { it.source() }
            .toSet()
        }
      }
    file
      .stream()
      .map { it.name }
      .filter {
        it.endsWith(".class") &&
          !it.endsWith("module-info.class") &&
          !it.endsWith("package-info.class")
      }
      .map { it.removeSuffix(".class").replace('/', '.') }
      .filter { name -> exported == null || name.substringBeforeLast('.') in exported }
      .sorted()
      .toList()
  }

/** A class a caller can name: public, or protected inside a class the caller can name. */
private fun accessible(type: Class<*>): Boolean {
  if (type.isSynthetic || type.isAnonymousClass || type.isLocalClass) return false
  val modifiers = type.modifiers
  val enclosing = type.declaringClass ?: return Modifier.isPublic(modifiers)
  return (Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers)) && accessible(enclosing)
}

private fun visible(modifiers: Int): Boolean =
  Modifier.isPublic(modifiers) || Modifier.isProtected(modifiers)

internal class JavaClass(private val type: Class<*>) {
  private val name = className(type)

  fun lines(): List<String> = listOf(header()) + members().map { "$name: $it" }.sorted()

  private fun header(): String {
    val kind =
      when {
        type.isAnnotation -> "@interface"
        type.isInterface -> "interface"
        type.isEnum -> "enum"
        type.isRecord -> "record"
        else -> "class"
      }
    val implicit =
      when (kind) {
        "@interface",
        "interface" -> Modifier.ABSTRACT or Modifier.STATIC
        "enum",
        "record" -> Modifier.FINAL or Modifier.STATIC
        else -> 0
      }
    val modifiers =
      type.modifiers and implicit.inv() and (Modifier.INTERFACE or Modifier.STRICT).inv()
    val words = mutableListOf<String>()
    words += effectiveNullScope()
    deprecated(type)?.let(words::add)
    words += modifierWords(modifiers)
    if (type.isSealed) words += "sealed"
    else if (!Modifier.isFinal(type.modifiers) && sealedParent()) words += "non-sealed"
    words += kind
    val head =
      StringBuilder(words.joinToString(" "))
        .append(' ')
        .append(name)
        .append(typeParameters(type.typeParameters))
    if (type.isRecord) {
      head.append(
        type.recordComponents.joinToString(", ", "(", ")") {
          "${type(it.annotatedType)} ${it.name}"
        },
      )
    }
    val superclass = type.annotatedSuperclass
    if (
      superclass != null && superclass.type !in IMPLICIT_SUPERCLASSES && !isEnumBase(superclass)
    ) {
      head.append(" extends ").append(type(superclass))
    }
    val interfaces =
      type.annotatedInterfaces.filterNot { type.isAnnotation && it.type == Annotation::class.java }
    if (interfaces.isNotEmpty()) {
      head.append(if (type.isInterface) " extends " else " implements ")
      head.append(interfaces.joinToString(", ") { type(it) })
    }
    type.permittedSubclasses?.let { permitted ->
      head.append(" permits ").append(permitted.map(::className).sorted().joinToString(", "))
    }
    return head.toString()
  }

  /**
   * The JSpecify scope that holds the class: its own `@NullMarked` or `@NullUnmarked`, else that of
   * the nearest enclosing class, else that of its package. An unannotated type use means "not null"
   * in a marked scope and "unknown" in an unmarked one, so a scope change changes every signature
   * in the class. The header records it so that such a change changes the file.
   */
  private fun effectiveNullScope(): String {
    var current: Class<*>? = type
    while (current != null) {
      nullScope(current)?.let {
        return it
      }
      current = current.declaringClass
    }
    // The reader loads the jars into the unnamed module, so it cannot see an annotation on
    // module-info. `verifyNullMarked` requires `@NullMarked` on every package instead.
    return type.`package`?.let(::nullScope) ?: "@NullUnmarked"
  }

  private fun sealedParent(): Boolean =
    (listOfNotNull(type.superclass) + type.interfaces).any { it.isSealed }

  private fun isEnumBase(superclass: AnnotatedType): Boolean =
    type.isEnum && (superclass.type as? ParameterizedType)?.rawType == Enum::class.java

  private fun members(): List<String> = buildList {
    for (field in type.declaredFields) {
      if (field.isSynthetic || !visible(field.modifiers)) continue
      add(field(field))
    }
    for (constructor in type.declaredConstructors) {
      if (constructor.isSynthetic || !visible(constructor.modifiers)) continue
      add(executable(constructor))
    }
    for (method in type.declaredMethods) {
      if (method.isSynthetic || method.isBridge || !visible(method.modifiers)) continue
      add(executable(method))
    }
  }

  private fun field(field: Field): String {
    if (field.isEnumConstant) return "enum constant ${field.name}"
    val words =
      listOfNotNull(deprecated(field)) + modifierWords(field.modifiers and FIELD_MODIFIERS)
    val line = "${words.joinToString(" ")} ${type(field.annotatedType)} ${field.name}"
    return constant(field)?.let { "$line = $it" } ?: line
  }

  private fun executable(executable: Executable): String {
    val words = mutableListOf<String>()
    nullScope(executable)?.let(words::add)
    deprecated(executable)?.let(words::add)
    val modifiers = executable.modifiers
    words += if (Modifier.isPublic(modifiers)) "public" else "protected"
    if (executable is Method) {
      when {
        type.isInterface && executable.isDefault -> words += "default"
        type.isInterface && Modifier.isAbstract(modifiers) -> words += "abstract"
        Modifier.isAbstract(modifiers) -> words += "abstract"
      }
      if (Modifier.isStatic(modifiers)) words += "static"
      if (Modifier.isFinal(modifiers)) words += "final"
    }
    typeParameters(executable.typeParameters).takeIf { it.isNotEmpty() }?.let { words += it.trim() }
    if (executable is Method) words += type(executable.annotatedReturnType)
    val parameters = executable.annotatedParameterTypes.map { type(it) }.toMutableList()
    if (executable.isVarArgs)
      parameters[parameters.lastIndex] = parameters.last().removeSuffix("[]") + "..."
    val simpleName = if (executable is Constructor<*>) type.simpleName else executable.name
    val line = StringBuilder(words.joinToString(" ")).append(' ').append(simpleName)
    line.append(parameters.joinToString(", ", "(", ")"))
    val exceptions = executable.annotatedExceptionTypes
    if (exceptions.isNotEmpty())
      line.append(" throws ").append(exceptions.joinToString(", ") { type(it) })
    if (executable is Method)
      executable.defaultValue?.let { line.append(" default ").append(literal(it)) }
    return line.toString()
  }

  private companion object {
    val IMPLICIT_SUPERCLASSES = setOf(Any::class.java, Record::class.java)
    const val FIELD_MODIFIERS =
      Modifier.PUBLIC or
        Modifier.PROTECTED or
        Modifier.STATIC or
        Modifier.FINAL or
        Modifier.VOLATILE or
        Modifier.TRANSIENT
  }
}

/**
 * The value of a compile-time constant. javac copies such a value into the caller's class file, so
 * a changed value changes compiled callers.
 */
private fun constant(field: Field): String? {
  val modifiers = field.modifiers
  if (!Modifier.isStatic(modifiers) || !Modifier.isFinal(modifiers)) return null
  if (!field.type.isPrimitive && field.type != String::class.java) return null
  field.isAccessible = true
  return literal(field.get(null))
}

private fun literal(value: Any?): String =
  when (value) {
    null -> "null"
    is String -> '"' + value.flatMap { escape(it) }.joinToString("") + '"'
    is Char -> "'" + escape(value).joinToString("") + "'"
    is Long -> "${value}L"
    is Float -> "${value}F"
    is Array<*> -> value.joinToString(", ", "{", "}") { literal(it) }
    // An annotation default can be a primitive array, which has no readable toString.
    is BooleanArray,
    is ByteArray,
    is ShortArray,
    is IntArray,
    is LongArray,
    is FloatArray,
    is DoubleArray,
    is CharArray ->
      (0 until java.lang.reflect.Array.getLength(value)).joinToString(", ", "{", "}") {
        literal(java.lang.reflect.Array.get(value, it))
      }
    is Class<*> -> className(value) + ".class"
    is Enum<*> -> "${className(value.declaringJavaClass)}.${value.name}"
    else -> value.toString()
  }

private fun escape(char: Char): List<Char> =
  when {
    char == '"' || char == '\\' || char == '\'' -> listOf('\\', char)
    char.code < 0x20 || char.code > 0x7e -> "\\u%04x".format(char.code).toList()
    else -> listOf(char)
  }

/**
 * The modifier keywords of a set of modifier bits, in the order of the Java Language Specification.
 * Java 27 deprecates `Modifier.toString`, and every compiler warning here is an error.
 */
internal fun modifierWords(modifiers: Int): List<String> =
  MODIFIER_WORDS.filter { (bit, _) -> modifiers and bit != 0 }.map { it.second }

private val MODIFIER_WORDS =
  listOf(
    Modifier.PUBLIC to "public",
    Modifier.PROTECTED to "protected",
    Modifier.PRIVATE to "private",
    Modifier.ABSTRACT to "abstract",
    Modifier.STATIC to "static",
    Modifier.FINAL to "final",
    Modifier.TRANSIENT to "transient",
    Modifier.VOLATILE to "volatile",
    Modifier.SYNCHRONIZED to "synchronized",
    Modifier.NATIVE to "native",
    Modifier.STRICT to "strictfp",
    Modifier.INTERFACE to "interface",
  )

/** The JSpecify scope annotation written on an element itself, if any. */
private fun nullScope(element: AnnotatedElement): String? =
  element.annotations
    .map { it.annotationClass.java.name }
    .firstOrNull { it == NULL_MARKED || it == NULL_UNMARKED }
    ?.let { "@" + it.substringAfterLast('.') }

private const val NULL_MARKED = "org.jspecify.annotations.NullMarked"
private const val NULL_UNMARKED = "org.jspecify.annotations.NullUnmarked"

private fun deprecated(element: AnnotatedElement): String? =
  if (element.isAnnotationPresent(java.lang.Deprecated::class.java)) "@Deprecated" else null

private fun className(type: Class<*>): String = type.canonicalName ?: type.name

private fun typeParameters(parameters: Array<out TypeVariable<*>>): String {
  if (parameters.isEmpty()) return ""
  return parameters.joinToString(", ", "<", ">") { parameter ->
    val bounds =
      parameter.annotatedBounds.filterNot { it.type == Any::class.java && it.annotations.isEmpty() }
    if (bounds.isEmpty()) parameter.name
    else parameter.name + " extends " + bounds.joinToString(" & ") { type(it) }
  }
}

/** The JSpecify nullness annotations on one type use, each with a trailing space. */
private fun nullness(type: AnnotatedType): String =
  type.annotations
    .filter { it.annotationClass.java.packageName == "org.jspecify.annotations" }
    .map { "@" + it.annotationClass.java.simpleName + " " }
    .sorted()
    .joinToString("")

/** One type use as source would write it, with its nullness annotations. */
internal fun type(type: AnnotatedType): String =
  when (type) {
    // JSpecify reads `String @Nullable []` as a nullable array of strings.
    is AnnotatedArrayType ->
      type(type.annotatedGenericComponentType) +
        nullness(type).let { if (it.isEmpty()) "" else " " + it.trim() + " " } +
        "[]"
    is AnnotatedParameterizedType -> {
      val raw = (type.type as ParameterizedType).rawType as Class<*>
      val arguments = type.annotatedActualTypeArguments
      val tail =
        if (arguments.isEmpty()) "" else arguments.joinToString(", ", "<", ">") { type(it) }
      // An inner class of a generic class carries the arguments of its owner, as in
      // `Outer<String>.Inner`. A changed owner argument is a changed type.
      val owner = type.annotatedOwnerType
      if (owner is AnnotatedParameterizedType) {
        type(owner) + "." + nullness(type) + raw.simpleName + tail
      } else {
        nullness(type) + className(raw) + tail
      }
    }
    is AnnotatedWildcardType -> {
      val lower = type.annotatedLowerBounds
      val upper =
        type.annotatedUpperBounds.filterNot {
          it.type == Any::class.java && it.annotations.isEmpty()
        }
      nullness(type) +
        when {
          lower.isNotEmpty() -> "? super " + lower.joinToString(" & ") { type(it) }
          upper.isNotEmpty() -> "? extends " + upper.joinToString(" & ") { type(it) }
          else -> "?"
        }
    }
    is AnnotatedTypeVariable -> nullness(type) + (type.type as TypeVariable<*>).name
    else -> nullness(type) + className(type.type as Class<*>)
  }

/**
 * Each `workhorse.*` property of a jar's Spring configuration metadata, with its type and default.
 *
 * The configuration processor writes that file from the property classes, so it is the list of
 * names that Spring Boot itself reads. The processor misses some defaults, such as an empty list,
 * and a hand-kept file can add others. So the default comes from the built class instead: the
 * reader makes a new root properties object and reads each property through its getters.
 */
private fun properties(jar: Path, loader: ClassLoader): List<String>? =
  JarFile(jar.toFile()).use { file ->
    val entry = file.getJarEntry("META-INF/spring-configuration-metadata.json") ?: return null
    val metadata: JsonNode =
      file.getInputStream(entry).use { JsonMapper.builder().build().readTree(it) }
    propertyLines(metadata, loader)
  }

/** One line for each property of parsed configuration metadata, with its default from `loader`. */
internal fun propertyLines(metadata: JsonNode, loader: ClassLoader): List<String> {
  val roots =
    metadata
      .get("groups")
      .values()
      .filterNot { it.has("sourceMethod") }
      .associate { group ->
        val type = Class.forName(group.get("type").asString(), true, loader)
        group.get("name").asString() to type.getDeclaredConstructor().newInstance()
      }
  return metadata.get("properties").values().map { property ->
    val name = property.get("name").asString()
    val line = StringBuilder("property ").append(name)
    property.get("type")?.let { line.append(": ").append(it.asString()) }
    defaultValue(name, roots)?.let { line.append(" = ").append(it) }
    if (property.has("deprecation")) line.append(" (deprecated)")
    line.toString()
  }
}

/** Reads `workhorse.worker.lease` as `getWorker().getLease()` on the root object of `workhorse`. */
private fun defaultValue(name: String, roots: Map<String, Any>): String? {
  val prefix =
    roots.keys.filter { name.startsWith("$it.") }.maxByOrNull { it.length }
      ?: throw IllegalStateException("no properties class owns $name")
  var value: Any? = roots.getValue(prefix)
  for (segment in name.removePrefix("$prefix.").split('.')) {
    val target = value ?: return null
    val camel =
      segment.split('-').joinToString("") { part -> part.replaceFirstChar(Char::uppercaseChar) }
    val getter =
      listOf("get$camel", "is$camel").firstNotNullOfOrNull { getter ->
        target.javaClass.methods.firstOrNull { it.name == getter && it.parameterCount == 0 }
      } ?: throw IllegalStateException("${target.javaClass.name} has no getter for $name")
    value = getter.invoke(target)
  }
  return value?.let(::propertyValue)
}

private fun propertyValue(value: Any): String =
  when (value) {
    is Boolean,
    is Number -> value.toString()
    is Collection<*> -> value.joinToString(", ", "[", "]") { it?.let(::propertyValue) ?: "null" }
    is Enum<*> -> value.name
    else -> literal(value.toString())
  }

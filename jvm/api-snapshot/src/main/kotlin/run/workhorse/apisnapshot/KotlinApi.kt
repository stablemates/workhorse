/** Every public declaration of the `.kt` files under a source directory. */
internal fun kotlinSnapshot(sources: Path): String {
  val paths =
    Files.walk(sources).use { walk -> walk.filter { it.extension == "kt" }.sorted().toList() }
  return render(
    KOTLIN_HEADER,
    kotlinSections(
      paths.map { sources.relativize(it).invariantSeparatorsPathString to it.readText() },
    ),
  )
}

/** The sections for the given `(name, text)` source files. */
internal fun kotlinSections(files: List<Pair<String, String>>): List<List<String>> {
  val disposable = Disposer.newDisposable("api-snapshot")
  try {
    // The reader only parses. It resolves nothing and compiles nothing, so the environment needs no
    // configuration beyond an empty set of compiler plugins.
    val configuration =
      CompilerConfiguration().apply {
        extensionsStorage = CompilerPluginRegistrar.ExtensionStorage()
      }
    val environment =
      KotlinCoreEnvironment.createForProduction(
        disposable,
        configuration,
        EnvironmentConfigFiles.JVM_CONFIG_FILES,
      )
    val factory = KtPsiFactory(environment.project, markGenerated = false)
    val parsed = files.map { (name, text) -> factory.createFile(name, text.replace("\r\n", "\n")) }
    val declared =
      parsed
        .groupBy(
          { it.packageFqName.asString() },
          { file -> file.declarations.filterIsInstance<KtClassOrObject>().mapNotNull { it.name } },
        )
        .mapValues { (_, names) ->
          names.flatten().toSet()
        }
    val topLevel = sortedMapOf<String, MutableList<String>>()
    val classes = mutableListOf<Pair<String, List<String>>>()
    for (file in parsed) {
      val reader = KotlinFile(file, declared[file.packageFqName.asString()].orEmpty())
      val pkg = file.packageFqName.asString()
      for (declaration in file.declarations) {
        if (!published(declaration)) continue
        if (declaration is KtClassOrObject)
          classes += reader.classSections(declaration, pkg, emptySet())
        else
          topLevel.getOrPut(pkg) { mutableListOf() } += reader.member(declaration, pkg, emptySet())
      }
    }
    val packages = topLevel.map { (pkg, lines) -> listOf("package $pkg") + lines }
    return packages + classes.sortedBy { it.first }.map { it.second }
  } finally {
    Disposer.dispose(disposable)
  }
}

/**
 * Whether a caller outside the module depends on a declaration.
 *
 * A public or protected declaration does. So does an `internal` one marked `@PublishedApi`, because
 * a public inline function compiles a call to it into the caller.
 */
private fun published(declaration: KtDeclaration): Boolean {
  if (declaration.hasModifier(KtTokens.PRIVATE_KEYWORD)) return false
  if (declaration.hasModifier(KtTokens.INTERNAL_KEYWORD))
    return annotationNames(declaration).contains("PublishedApi")
  return true
}

private fun annotationNames(owner: KtModifierListOwner): List<String> =
  owner.annotationEntries.mapNotNull { it.shortName?.asString() }

/**
 * The source of an expression or annotation on one line. Whitespace and comments outside string
 * literals become one space or nothing, because they do not change the value. A string literal
 * keeps every character, because each one is part of the value. Inside a literal, `%` shows as
 * `%25`, a line feed as `%0A`, and a carriage return as `%0D`. So the line stays one line, and two
 * different literals never give the same text.
 */
private fun oneLine(element: PsiElement): String = buildString { flatten(element, this) }.trim()

private fun flatten(element: PsiElement, out: StringBuilder) {
  when {
    element is KtStringTemplateExpression ->
      out.append(element.text.replace("%", "%25").replace("\n", "%0A").replace("\r", "%0D"))
    element is PsiWhiteSpace -> if (out.isNotEmpty() && out.last() != ' ') out.append(' ')
    element is PsiComment -> Unit
    element.firstChild == null -> out.append(element.text)
    else -> {
      var child: PsiElement? = element.firstChild
      while (child != null) {
        flatten(child, out)
        child = child.nextSibling
      }
    }
  }
}

private class KotlinFile(file: KtFile, private val packageClasses: Set<String>) {
  private val pkg = file.packageFqName.asString()
  private val imports: Map<String, String> =
    file.importDirectives.associate { directive ->
      check(!directive.isAllUnder) {
        "${file.name} imports ${directive.importedFqName}.*; the snapshot reader needs every imported name"
      }
      val fqName =
        checkNotNull(directive.importedFqName) { "${file.name} has an import without a name" }
      (directive.aliasName ?: fqName.shortName().asString()) to fqName.asString()
    }

  /** The section of one class and the sections of its public nested classes, each with its name. */
  fun classSections(
    declaration: KtClassOrObject,
    owner: String,
    scope: Set<String>,
  ): List<Pair<String, List<String>>> {
    val name =
      if (declaration is KtObjectDeclaration && declaration.isCompanion())
        declaration.name ?: "Companion"
      else declaration.name
    val fqName = "$owner.$name"
    val inner = scope + typeParameterNames(declaration)
    val lines = mutableListOf(header(declaration, fqName, inner))
    val nested = mutableListOf<Pair<String, List<String>>>()
    implicitConstructor(declaration)?.let { lines += "$fqName: $it" }
    declaration.primaryConstructor?.let { constructor ->
      if (published(constructor))
        lines +=
          "$fqName: " +
            modifiers(constructor) +
            "constructor" +
            parameters(constructor.valueParameters, inner)
      for (parameter in constructor.valueParameters) {
        if (parameter.hasValOrVar() && published(parameter))
          lines += "$fqName: " + constructorProperty(parameter, inner)
      }
    }
    for (member in declaration.declarations) {
      if (!published(member)) continue
      when (member) {
        is KtEnumEntry -> lines += "$fqName: enum entry ${member.name}"
        is KtClassOrObject ->
          nested +=
            classSections(
              member,
              fqName,
              if (member is KtClass && member.isInner()) inner else scope,
            )
        else -> lines += member(member, fqName, inner)
      }
    }
    return listOf(fqName to lines) + nested
  }

  private fun header(declaration: KtClassOrObject, fqName: String, scope: Set<String>): String {
    val kind =
      when {
        declaration is KtObjectDeclaration -> "object"
        declaration is KtClass && declaration.isInterface() -> "interface"
        else -> "class"
      }
    val implicitFinal =
      kind == "class" &&
        listOf(
            KtTokens.OPEN_KEYWORD,
            KtTokens.ABSTRACT_KEYWORD,
            KtTokens.SEALED_KEYWORD,
            KtTokens.ENUM_KEYWORD,
            KtTokens.ANNOTATION_KEYWORD,
          )
          .none {
            declaration.hasModifier(it)
          } &&
        !declaration.hasModifier(KtTokens.FINAL_KEYWORD)
    val head =
      StringBuilder(
        modifiers(
          declaration,
          implicit = if (implicitFinal) setOf(KtTokens.FINAL_KEYWORD) else emptySet(),
        ),
      )
    head.append(kind).append(' ').append(fqName).append(typeParameters(declaration, scope))
    val supertypes =
      declaration.superTypeListEntries.mapNotNull { it.typeReference }.map { type(it, scope) }
    if (supertypes.isNotEmpty()) head.append(" : ").append(supertypes.joinToString(", "))
    head.append(constraints(declaration, scope))
    return head.toString()
  }

  /** One top-level or member declaration, as `owner: line`. */
  fun member(declaration: KtDeclaration, owner: String, scope: Set<String>): String {
    val line =
      when (declaration) {
        is KtNamedFunction -> function(declaration, scope + typeParameterNames(declaration))
        is KtProperty -> property(declaration, scope + typeParameterNames(declaration))
        is KtSecondaryConstructor ->
          modifiers(declaration) + "constructor" + parameters(declaration.valueParameters, scope)
        is KtTypeAlias ->
          modifiers(declaration) +
            "typealias " +
            declaration.name +
            typeParameters(declaration, scope) +
            " = " +
            type(declaration.getTypeReference(), scope + typeParameterNames(declaration))
        else ->
          throw IllegalStateException(
            "the snapshot reader cannot read ${declaration.javaClass.simpleName} ${declaration.name}",
          )
      }
    return "$owner: $line"
  }

  private fun function(function: KtNamedFunction, scope: Set<String>): String {
    // An interface member without a body is abstract whether the source says so or not.
    val inInterface = (function.parent?.parent as? KtClass)?.isInterface() == true
    val implicit =
      if (inInterface && function.bodyExpression == null) setOf(KtTokens.ABSTRACT_KEYWORD)
      else emptySet()
    val line = StringBuilder(modifiers(function, implicit = implicit)).append("fun ")
    typeParameters(function, scope)
      .takeIf { it.isNotEmpty() }
      ?.let { line.append(it.trim()).append(' ') }
    receiver(function, scope)?.let { line.append(it).append('.') }
    line.append(function.name).append(parameters(function.valueParameters, scope))
    line.append(": ").append(function.typeReference?.let { type(it, scope) } ?: "Unit")
    line.append(constraints(function, scope))
    return line.toString()
  }

  /**
   * The constructor the compiler adds to a class that declares none. It is public, or protected in
   * a sealed class. Making it private breaks every caller that constructs the class, so it needs a
   * line like a written constructor.
   */
  private fun implicitConstructor(declaration: KtClassOrObject): String? {
    if (declaration !is KtClass || declaration.isInterface() || declaration.isEnum()) return null
    if (declaration.isAnnotation()) return null
    if (declaration.primaryConstructor != null || declaration.secondaryConstructors.isNotEmpty()) {
      return null
    }
    val sealed = declaration.hasModifier(KtTokens.SEALED_KEYWORD)
    return if (sealed) "protected constructor()" else "public constructor()"
  }

  private fun property(property: KtProperty, scope: Set<String>): String {
    // An interface property without a getter body is abstract, so every implementation must
    // supply it, whether the source writes `abstract` or not.
    val inInterface = (property.parent?.parent as? KtClass)?.isInterface() == true
    val implicit =
      if (inInterface && property.getter?.hasBody() != true && property.delegate == null) {
        setOf(KtTokens.ABSTRACT_KEYWORD)
      } else {
        emptySet()
      }
    val line =
      StringBuilder(modifiers(property, implicit = implicit))
        .append(if (property.isVar) "var " else "val ")
    typeParameters(property, scope)
      .takeIf { it.isNotEmpty() }
      ?.let { line.append(it.trim()).append(' ') }
    receiver(property, scope)?.let { line.append(it).append('.') }
    line
      .append(property.name)
      .append(": ")
      .append(
        type(
          checkNotNull(property.typeReference) { "${property.name} has no declared type" },
          scope,
        ),
      )
    property.initializer?.let { line.append(" = ").append(oneLine(it)) }
    property.delegateExpression?.let { line.append(" by ").append(oneLine(it)) }
    property.setter?.let { setter ->
      VISIBILITIES.firstOrNull { setter.hasModifier(it) }
        ?.let { line.append(" (").append(it.value).append(" set)") }
    }
    return line.toString()
  }

  private fun constructorProperty(parameter: KtParameter, scope: Set<String>): String =
    modifiers(parameter) +
      (if (parameter.isMutable) "var " else "val ") +
      parameter.name +
      ": " +
      type(checkNotNull(parameter.typeReference), scope)

  private fun receiver(callable: KtCallableDeclaration, scope: Set<String>): String? =
    callable.receiverTypeReference?.let { reference ->
      val text = type(reference, scope)
      if (reference.typeElement is KtFunctionType || reference.typeElement is KtNullableType)
        "($text)"
      else text
    }

  private fun parameters(parameters: List<KtParameter>, scope: Set<String>): String =
    parameters.joinToString(", ", "(", ")") { parameter ->
      val line = StringBuilder(modifiers(parameter, normalizeVisibility = false))
      line
        .append(parameter.name)
        .append(": ")
        .append(
          type(checkNotNull(parameter.typeReference) { "${parameter.name} has no type" }, scope),
        )
      parameter.defaultValue?.let { line.append(" = ").append(oneLine(it)) }
      line.toString()
    }

  private fun typeParameterNames(owner: KtTypeParameterListOwner): Set<String> =
    owner.typeParameters.mapNotNull { it.name }.toSet()

  private fun typeParameters(owner: KtTypeParameterListOwner, scope: Set<String>): String {
    val parameters = owner.typeParameters
    if (parameters.isEmpty()) return ""
    val names = scope + typeParameterNames(owner)
    return parameters.joinToString(", ", "<", ">") { parameter ->
      val line =
        StringBuilder(modifiers(parameter, normalizeVisibility = false)).append(parameter.name)
      parameter.extendsBound?.let { line.append(" : ").append(type(it, names)) }
      line.toString()
    }
  }

  private fun constraints(owner: KtTypeParameterListOwner, scope: Set<String>): String {
    val constraints = owner.typeConstraints
    if (constraints.isEmpty()) return ""
    val names = scope + typeParameterNames(owner)
    return " where " +
      constraints.joinToString(", ") {
        "${it.subjectTypeParameterName?.getReferencedName()} : ${type(checkNotNull(it.boundTypeReference), names)}"
      }
  }

  /**
   * The annotations and modifier keywords of a declaration, each followed by a space. A declaration
   * without a visibility keyword is public, so the line says `public` whether the source does or
   * not. `implicit` names the keywords the declaration has without writing them.
   */
  private fun modifiers(
    owner: KtModifierListOwner,
    normalizeVisibility: Boolean = true,
    implicit: Set<KtModifierKeywordToken> = emptySet(),
  ): String {
    val words = mutableListOf<String>()
    owner.annotationEntries
      .filter { it.shortName?.asString() !in QUIET_ANNOTATIONS }
      .forEach { words += oneLine(it) }
    if (normalizeVisibility && VISIBILITIES.none { owner.hasModifier(it) }) words += "public"
    MODIFIERS.filter { owner.hasModifier(it) || it in implicit }.forEach { words += it.value }
    return words.joinToString("") { "$it " }
  }

  fun type(reference: KtTypeReference?, scope: Set<String>): String {
    checkNotNull(reference) { "a declaration has no type" }
    return typeModifiers(reference.modifierList, scope) + element(reference.typeElement, scope)
  }

  private fun typeModifiers(list: KtModifierList?, scope: Set<String>): String {
    if (list == null) return ""
    val words =
      list.annotationEntries.map { oneLine(it) } +
        MODIFIERS.filter { list.hasModifier(it) }.map { it.value }
    return words.joinToString("") { "$it " }
  }

  private fun element(element: KtTypeElement?, scope: Set<String>): String =
    when (element) {
      is KtNullableType -> {
        val inner = element.innerType
        val text = typeModifiers(element.modifierList, scope) + element(inner, scope)
        if (inner is KtFunctionType || element.modifierList != null) "($text)?" else "$text?"
      }
      is KtUserType -> userType(element, scope)
      is KtFunctionType -> {
        val receiver = element.receiverTypeReference?.let { type(it, scope) + "." } ?: ""
        val parameters =
          element.parameters.joinToString(", ", "(", ")") { type(it.typeReference, scope) }
        "$receiver$parameters -> ${type(element.returnTypeReference, scope)}"
      }
      is KtIntersectionType ->
        element(element.getLeftTypeRef()?.typeElement, scope) +
          " & " +
          element(element.getRightTypeRef()?.typeElement, scope)
      else ->
        throw IllegalStateException("the snapshot reader cannot read the type ${element?.text}")
    }

  private fun userType(type: KtUserType, scope: Set<String>): String {
    val segments = generateSequence(type) { it.qualifier }.toList().reversed()
    val first = checkNotNull(segments.first().referencedName)
    val qualified =
      when {
        segments.size == 1 && first in scope -> first
        first in imports -> imports.getValue(first)
        first in packageClasses -> "$pkg.$first"
        else -> first
      }
    return segments.withIndex().joinToString(".") { (index, segment) ->
      val name = if (index == 0) qualified else checkNotNull(segment.referencedName)
      val arguments = segment.typeArguments
      if (arguments.isEmpty()) name
      else
        name +
          arguments.joinToString(", ", "<", ">") { projection ->
            when (projection.projectionKind) {
              KtProjectionKind.STAR -> "*"
              KtProjectionKind.IN -> "in " + type(projection.typeReference, scope)
              KtProjectionKind.OUT -> "out " + type(projection.typeReference, scope)
              KtProjectionKind.NONE -> type(projection.typeReference, scope)
            }
          }
    }
  }
}

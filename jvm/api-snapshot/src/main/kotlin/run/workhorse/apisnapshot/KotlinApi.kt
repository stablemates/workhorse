private const val KOTLIN_HEADER =
  """# Public Kotlin API
#
# Generated by `pnpm kotlin-api:generate` from the sources of the workhorse-kotlin jar. ADR 0054 and
# ADR 0103 govern this surface: a removed or renamed public declaration, a changed default
# argument, and a narrowed signature are breaking, and an addition is not.
#
# Each line is one public declaration, or one `@PublishedApi internal` declaration that a public
# inline function calls. A member line starts with the name of the class that declares it, and a
# top-level line with the package. A type name that the file imports or that the package declares
# is fully qualified. Any other name is a Kotlin default import or a type parameter.
"""

/** Annotations that change no caller: they only steer the compiler inside this module. */
private val QUIET_ANNOTATIONS = setOf("Suppress", "OptIn")


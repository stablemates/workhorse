"""Render the public Python API of ``workhorse`` as a stable text snapshot.

ADR 0054 defines the Python API as the names in a public module's ``__all__``. This tool reproduces
that definition: it walks the installed package for modules whose every path segment avoids a
leading underscore, reads each one's ``__all__``, and prints the shape a caller reaches through each
name. ``scripts/generate-python-api.ts`` writes the result to ``api/python.txt``, so a removed name
or a narrowed signature shows up as a deleted or changed line.

Introspection rather than parsing, because ``__all__`` re-exports across modules and only the
imported object knows where it was defined. Inherited members are printed with declared ones: a
caller reaches them the same way, so dropping a base class is as breaking as deleting the member.
"""

from __future__ import annotations

import argparse
import ast
import importlib
import inspect
import pkgutil
import re
import sys
import textwrap
import types
import typing
from collections.abc import Callable, Sequence
from pathlib import Path

HEADER = """# Public Python API
#
# Generated by `pnpm python-api:generate` from the installed `workhorse` package. ADR 0054 governs
# this surface: a removed or renamed name in a public module's `__all__` and a narrowed signature
# are breaking, and an addition is not. An underscore-prefixed module is private and absent here.
"""

# Dunder members a caller calls directly, so they belong to the surface.
PROTOCOL_MEMBERS = frozenset(
    {
        "__aenter__",
        "__aexit__",
        "__aiter__",
        "__anext__",
        "__call__",
        "__enter__",
        "__exit__",
        "__init__",
        "__iter__",
        "__next__",
    }
)

# Attributes Python puts on every class, every exception, or every dataclass.
IMPLICIT_MEMBERS = frozenset(
    {
        "add_note",
        "args",
        "count",
        "index",
        "mro",
        "with_traceback",
    }
)

# Builtin conversions whose call gives a value of that type, such as ``str(details["state"])``.
CONVERSIONS = frozenset(
    {"bool", "bytes", "dict", "float", "frozenset", "int", "list", "str", "tuple"}
)

# Module attributes whose value moves with every release. The snapshot keeps their name and type,
# because printing the value would make each version bump read as a removed line.
RELEASE_VALUES = frozenset({"__version__"})


def module_names(package: str) -> list[str]:
    """Public modules of a package, the package itself first, then depth-first by name."""
    root = importlib.import_module(package)
    found = [package]
    for info in pkgutil.walk_packages(root.__path__, prefix=f"{package}."):
        if any(segment.startswith("_") for segment in info.name.split(".")[1:]):
            continue
        found.append(info.name)
    return sorted(found)


class Renderer:
    """Renders one distribution's public modules, caching each module's parsed source."""

    def __init__(self) -> None:
        self._sources: dict[str, tuple[ast.Module | None, str]] = {}

    def _source(self, module_name: str) -> tuple[ast.Module | None, str]:
        if module_name not in self._sources:
            module = sys.modules.get(module_name)
            if module is None:
                self._sources[module_name] = (None, "")
            else:
                try:
                    text = inspect.getsource(module)
                except (OSError, TypeError):
                    self._sources[module_name] = (None, "")
                else:
                    self._sources[module_name] = (ast.parse(text), text)
        return self._sources[module_name]

    def type_alias_source(self, alias: typing.TypeAliasType) -> str | None:
        """The right-hand side of a ``type X = ...`` statement, exactly as written."""
        origin = getattr(alias, "__module__", None)
        if origin is None:
            return None
        tree, text = self._source(origin)
        if tree is None:
            return None
        for node in tree.body:
            if isinstance(node, ast.TypeAlias) and node.name.id == alias.__name__:
                return ast.get_source_segment(text, node.value)
        return None

    def annotation(self, value: object) -> str:
        """A source-shaped rendering of one annotation.

        Modules that import ``annotations`` from ``__future__`` store the text a reader wrote, and
        the rest store the object it evaluates to. Normalising the second form to the first keeps
        one module's move to postponed evaluation out of the snapshot.
        """
        if isinstance(value, str):
            return value
        if value is None:
            return "None"
        if isinstance(value, type) and value.__module__ == "builtins":
            return value.__qualname__
        rendered = repr(value) if not isinstance(value, type) else f"{value.__qualname__}"
        return re.sub(
            r"\b(?:typing|collections\.abc|workhorse[\w.]*|datetime|decimal)\.", "", rendered
        )

    def signature(self, name: str, function: Callable[..., object]) -> str:
        """One ``def`` line, with every annotation rendered the way the source writes it."""
        try:
            signature = inspect.signature(function)
        except (TypeError, ValueError):
            return f"def {name}(...)"
        rendered: list[str] = []
        for parameter in signature.parameters.values():
            text = parameter.name
            if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
                text = f"*{text}"
            elif parameter.kind is inspect.Parameter.VAR_KEYWORD:
                text = f"**{text}"
            elif parameter.kind is inspect.Parameter.KEYWORD_ONLY and "*" not in rendered:
                rendered.append("*")
            if parameter.annotation is not inspect.Parameter.empty:
                text = f"{text}: {self.annotation(parameter.annotation)}"
            if parameter.default is not inspect.Parameter.empty:
                separator = " = " if parameter.annotation is not inspect.Parameter.empty else "="
                text = f"{text}{separator}{self.value(parameter.default)}"
            rendered.append(text)
        returns = (
            ""
            if signature.return_annotation is inspect.Signature.empty
            else f" -> {self.annotation(signature.return_annotation)}"
        )
        prefix = "async def" if inspect.iscoroutinefunction(function) else "def"
        return f"{prefix} {name}({', '.join(rendered)}){returns}"

    def value(self, value: object) -> str:
        """A default or constant, printed when its identity is stable and named otherwise."""
        if isinstance(value, str | int | float | bool | bytes | None):
            return repr(value)
        if isinstance(value, tuple | frozenset) and not value:
            return repr(value)
        if isinstance(value, type):
            return value.__qualname__
        if callable(value) and hasattr(value, "__name__"):
            return f"<{value.__name__}>"
        return f"<{type(value).__qualname__}>"

    def init_attributes(self, cls: type, declared: frozenset[str] = frozenset()) -> dict[str, str]:
        """Public attributes that the ``workhorse`` ``__init__`` chain assigns on ``self``.

        A caller reads ``error.code`` or ``error.retry_after_ms`` the same way as an annotated
        attribute, but neither ``dir`` nor the class annotations show it. So the tool reads the
        ``__init__`` that construction runs in the order that it runs. A call to
        ``super().__init__`` or ``Base.__init__(self, ...)`` runs that base ``__init__`` at the
        place of the call, and a base ``__init__`` that the chain does not call assigns nothing.

        The type of an attribute is the type of the last assignment that always runs. An assignment
        inside a branch or a loop can run or not, so it adds its type to the types that the line
        states, such as ``int | str``. The type of one assignment is the annotation of the
        assignment, the annotation of the ``__init__`` parameter that it copies, the builtin that
        converts the value, the type argument of ``typing.cast``, or the type of a literal.
        Otherwise it is ``<unannotated>``. A name in ``declared`` already has a line, so it is left
        out.
        """
        mro = cls.__mro__
        possible: dict[str, set[str]] = {}
        self._run_initializer(mro, _initializer_index(mro, 0), possible, True, frozenset())
        return {
            name: " | ".join(sorted(kinds))
            for name, kinds in possible.items()
            if name not in declared
        }

    def _run_initializer(
        self,
        mro: tuple[type, ...],
        index: int | None,
        possible: dict[str, set[str]],
        always: bool,
        active: frozenset[int],
    ) -> None:
        """Read one ``__init__`` of the chain, and each base ``__init__`` that it calls."""
        if index is None or index in active:
            return
        base = mro[index]
        initializer = vars(base)["__init__"]
        if not base.__module__.startswith("workhorse") or not inspect.isfunction(initializer):
            return
        try:
            source = textwrap.dedent(inspect.getsource(initializer))
        except (OSError, TypeError):
            return
        definition = ast.parse(source).body[0]
        if not isinstance(definition, ast.FunctionDef | ast.AsyncFunctionDef):
            return
        context = _InitializerContext(
            mro=mro,
            position=index,
            names=initializer.__globals__,
            parameters=inspect.signature(initializer).parameters,
            active=active | {index},
        )
        self._run_statements(definition.body, context, possible, always)

    def _run_statements(
        self,
        body: list[ast.stmt],
        context: _InitializerContext,
        possible: dict[str, set[str]],
        always: bool,
    ) -> None:
        """Apply the assignments and base calls of a block in order."""
        for statement in body:
            if isinstance(statement, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
                continue
            if isinstance(statement, ast.Assign | ast.AnnAssign):
                targets = (
                    statement.targets if isinstance(statement, ast.Assign) else [statement.target]
                )
                for target in targets:
                    if (
                        isinstance(target, ast.Attribute)
                        and isinstance(target.value, ast.Name)
                        and target.value.id == "self"
                        and not target.attr.startswith("_")
                    ):
                        kind = self._assigned_type(statement, statement.value, context.parameters)
                        if always:
                            possible[target.attr] = {kind}
                        else:
                            possible.setdefault(target.attr, set()).add(kind)
                continue
            if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call):
                called = _called_initializer(
                    statement.value, context.mro, context.position, context.names
                )
                if called is not None:
                    self._run_initializer(context.mro, called, possible, always, context.active)
                    continue
            # A `with` block and the body of a `try` run whenever construction succeeds. A branch,
            # a loop, an `else`, and a handler can run or not.
            for field in ("body", "orelse", "finalbody"):
                nested = getattr(statement, field, None)
                if not isinstance(nested, list):
                    continue
                runs = always and (
                    (field == "body" and isinstance(statement, ast.With | ast.AsyncWith | ast.Try))
                    or field == "finalbody"
                )
                self._run_statements(
                    [item for item in nested if isinstance(item, ast.stmt)], context, possible, runs
                )
            for handler in getattr(statement, "handlers", []):
                if isinstance(handler, ast.ExceptHandler):
                    self._run_statements(handler.body, context, possible, False)
            if isinstance(statement, ast.Match):
                for case in statement.cases:
                    self._run_statements(case.body, context, possible, False)

    def _assigned_type(
        self,
        statement: ast.Assign | ast.AnnAssign,
        value: ast.expr | None,
        parameters: typing.Mapping[str, inspect.Parameter],
    ) -> str:
        if isinstance(statement, ast.AnnAssign):
            annotation = statement.annotation
            # `"str"` and `str` are one annotation; the quotes only defer its evaluation.
            if isinstance(annotation, ast.Constant) and isinstance(annotation.value, str):
                return annotation.value
            return ast.unparse(annotation)
        if isinstance(value, ast.Name) and value.id in parameters:
            annotation = parameters[value.id].annotation
            if annotation is not inspect.Parameter.empty:
                return self.annotation(annotation)
        if (
            isinstance(value, ast.Call)
            and isinstance(value.func, ast.Name)
            and value.func.id in CONVERSIONS
        ):
            return value.func.id
        # `cast(int, value)` states the type of its result.
        if isinstance(value, ast.Call) and value.args and _names_cast(value.func):
            target = value.args[0]
            if isinstance(target, ast.Constant) and isinstance(target.value, str):
                return target.value
            return ast.unparse(target)
        if isinstance(value, ast.Constant) and value.value is not None:
            return type(value.value).__qualname__
        return "<unannotated>"

    def members(self, cls: type) -> list[str]:
        """Every member a caller reaches on a class, own and inherited, sorted by name."""
        annotations: dict[str, object] = {}
        for base in reversed(cls.__mro__):
            if base is object:
                continue
            annotations.update(inspect.get_annotations(base))
        names = {name for name in dir(cls) if not name.startswith("_")}
        names |= {name for name in dir(cls) if name in PROTOCOL_MEMBERS}
        names |= {name for name in annotations if not name.startswith("_")}
        names -= IMPLICIT_MEMBERS
        assigned = self.init_attributes(cls, frozenset(names))
        names |= assigned.keys()
        lines: list[str] = []
        for name in sorted(names):
            attribute = inspect.getattr_static(cls, name, None)
            if isinstance(attribute, property):
                getter = attribute.fget
                returns = "" if getter is None else self.signature(name, getter).split(") ", 1)[-1]
                lines.append(f"  @property {name}{'' if not returns else f' {returns}'}")
            elif isinstance(attribute, staticmethod | classmethod):
                kind = "staticmethod" if isinstance(attribute, staticmethod) else "classmethod"
                lines.append(f"  @{kind} {self.signature(name, attribute.__func__)}")
            elif inspect.isroutine(attribute):
                lines.append(f"  {self.signature(name, attribute)}")
            elif name in annotations:
                declared = f"  {name}: {self.annotation(annotations[name])}"
                if name in vars(cls):
                    declared = f"{declared} = {self.value(vars(cls)[name])}"
                lines.append(declared)
            elif name in assigned:
                lines.append(f"  {name}: {assigned[name]}  # set by __init__")
            else:
                lines.append(f"  {name} = {self.value(attribute)}")
        return lines

    def render(self, name: str, obj: object) -> list[str]:
        """One ``__all__`` name and, for a class, its members."""
        if isinstance(obj, typing.TypeAliasType):
            source = self.type_alias_source(obj)
            return [f"type {name} = {source if source else self.annotation(obj.__value__)}"]
        if typing.get_origin(obj) is not None or isinstance(obj, types.UnionType):
            return [f"type {name} = {self.annotation(obj)}"]
        if isinstance(obj, typing.TypeVar):
            bound = "" if obj.__bound__ is None else f" bound={self.annotation(obj.__bound__)}"
            return [f"typevar {name}{bound}"]
        if isinstance(obj, type):
            bases = [base.__qualname__ for base in obj.__bases__ if base is not object]
            heritage = f"({', '.join(bases)})" if bases else ""
            return [f"class {name}{heritage}", *self.members(obj)]
        if inspect.isroutine(obj):
            return [self.signature(name, obj)]
        if callable(obj) and not isinstance(obj, types.ModuleType):
            return [f"callable {name}: {self.annotation(type(obj))}"]
        if name in RELEASE_VALUES:
            return [f"{name}: {self.annotation(type(obj))}"]
        return [f"{name}: {self.annotation(type(obj))} = {self.value(obj)}"]

    def module(self, module_name: str) -> str:
        """One module's heading and every name its ``__all__`` promises."""
        module = importlib.import_module(module_name)
        exported = getattr(module, "__all__", None)
        if exported is None:
            raise SystemExit(
                f"{module_name} is public and declares no __all__; "
                "declare one or rename the module with a leading underscore"
            )
        blocks = ["\n".join(self.render(name, getattr(module, name))) for name in sorted(exported)]
        return f"## {module_name}\n\n" + "\n\n".join(blocks) + "\n"


class _InitializerContext(typing.NamedTuple):
    """What reading one ``__init__`` of the chain needs about it."""

    mro: tuple[type, ...]
    position: int
    names: dict[str, object]
    parameters: typing.Mapping[str, inspect.Parameter]
    active: frozenset[int]


def _names_cast(function: ast.expr) -> bool:
    """Whether a call names ``typing.cast``, as ``cast`` or as ``typing.cast``."""
    if isinstance(function, ast.Name):
        return function.id == "cast"
    return isinstance(function, ast.Attribute) and function.attr == "cast"


def _initializer_index(mro: tuple[type, ...], start: int) -> int | None:
    """The MRO position of the first class from ``start`` on that defines ``__init__``."""
    for index in range(start, len(mro)):
        if "__init__" in vars(mro[index]):
            return index
    return None


def _called_initializer(
    call: ast.Call, mro: tuple[type, ...], caller: int, names: dict[str, object]
) -> int | None:
    """The MRO position of the ``__init__`` that a call runs, or None for another call.

    ``super().__init__(...)`` runs the next ``__init__`` after the caller's class.
    ``Base.__init__(self, ...)`` runs the first ``__init__`` from ``Base`` on.
    """
    function = call.func
    if not (isinstance(function, ast.Attribute) and function.attr == "__init__"):
        return None
    owner = function.value
    if (
        isinstance(owner, ast.Call)
        and isinstance(owner.func, ast.Name)
        and owner.func.id == "super"
    ):
        if not owner.args:
            return _initializer_index(mro, caller + 1)
        named = owner.args[0]
        base = names.get(named.id) if isinstance(named, ast.Name) else None
        return _initializer_index(mro, mro.index(base) + 1) if base in mro else None
    if isinstance(owner, ast.Name):
        base = names.get(owner.id)
        return _initializer_index(mro, mro.index(base)) if base in mro else None
    return None


def render(package: str) -> str:
    """The whole snapshot, header first."""
    renderer = Renderer()
    return HEADER + "\n" + "\n".join(renderer.module(name) for name in module_names(package))


def main(argv: Sequence[str] | None = None) -> int:
    """Print the snapshot, or write it to a file when one is named."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=None, help="file to write instead of stdout")
    parser.add_argument("--package", default="workhorse", help="installed package to read")
    arguments = parser.parse_args(argv)
    snapshot = render(arguments.package)
    if arguments.output is None:
        sys.stdout.write(snapshot)
    else:
        arguments.output.write_text(snapshot, encoding="utf8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

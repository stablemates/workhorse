import { readdir, readFile } from "node:fs/promises";
import path from "node:path";

/** A manifest statement, as the C# catalogues read it. */
export interface CSharpStatement {
  readonly name: string;
  readonly arity: number;
  readonly contract: string;
  readonly catalogues: readonly string[];
}

/** The version and limit constants of the core catalogue. The dashboard catalogue has none. */
export interface CSharpConstants {
  readonly clientProtocolVersion: number;
  readonly minimumProtocolVersion: number;
  readonly maximumProtocolVersion: number;
  readonly minimumSchemaVersion: number;
  readonly maximumSchemaVersion: number;
  readonly maxEnqueueBatchSize: number;
  readonly defaultTaskValueMaxBytes: number;
}

export interface CSharpCatalogue {
  readonly namespace: string;
  readonly className: string;
  readonly summary: string;
  readonly statements: readonly CSharpStatement[];
  readonly constants?: CSharpConstants;
}

/** `claim_v1` becomes `ClaimV1`. */
export function csharpMemberName(statement: string): string {
  return statement
    .split("_")
    .map((part) => (part === "" ? "" : `${part[0]?.toUpperCase()}${part.slice(1)}`))
    .join("");
}

const constantNames: Record<keyof CSharpConstants, string> = {
  clientProtocolVersion: "ClientProtocolVersion",
  minimumProtocolVersion: "MinimumProtocolVersion",
  maximumProtocolVersion: "MaximumProtocolVersion",
  minimumSchemaVersion: "MinimumSchemaVersion",
  maximumSchemaVersion: "MaximumSchemaVersion",
  maxEnqueueBatchSize: "MaxEnqueueBatchSize",
  defaultTaskValueMaxBytes: "DefaultTaskValueMaxBytes",
};

/**
 * Writes one internal C# catalogue class (ADR 0107, "SQL comes from the generated catalogue").
 * Npgsql sends native positional placeholders, so each `$n` stays as it is, and a statement that
 * uses one `$n` twice binds the value once. JSON string escapes are valid C# string escapes, so
 * `JSON.stringify` writes each SQL literal.
 */
export function renderCSharpCatalogue(catalogue: CSharpCatalogue): string {
  const reserved = new Set(["Statement", "All", ...Object.values(constantNames)]);
  const seen = new Set<string>();
  for (const statement of catalogue.statements) {
    const member = csharpMemberName(statement.name);
    if (!/^[A-Z][A-Za-z0-9]*$/.test(member))
      throw new Error(`${statement.name} gives no valid C# member name`);
    if (seen.has(member) || reserved.has(member))
      throw new Error(`C# SQL catalogue member ${member} is not unique`);
    seen.add(member);
  }

  const constants = catalogue.constants;
  const constantLines =
    constants === undefined
      ? ""
      : `    /// <summary>The SQL protocol version this assembly implements.</summary>
    internal const int ${constantNames.clientProtocolVersion} = ${constants.clientProtocolVersion};

    internal const int ${constantNames.minimumProtocolVersion} = ${constants.minimumProtocolVersion};
    internal const int ${constantNames.maximumProtocolVersion} = ${constants.maximumProtocolVersion};
    internal const int ${constantNames.minimumSchemaVersion} = ${constants.minimumSchemaVersion};
    internal const int ${constantNames.maximumSchemaVersion} = ${constants.maximumSchemaVersion};

    /// <summary>PostgreSQL's atomic enqueue batch limit.</summary>
    internal const int ${constantNames.maxEnqueueBatchSize} = ${constants.maxEnqueueBatchSize};

    internal const long ${constantNames.defaultTaskValueMaxBytes} = ${constants.defaultTaskValueMaxBytes}L;

`;
  const entries = catalogue.statements
    .map(
      (statement) =>
        `    /// <summary><c>${statement.name}</c> (${statement.catalogues.join(", ")}).</summary>
    internal static readonly Statement ${csharpMemberName(statement.name)} = new(
        ${JSON.stringify(statement.name)},
        ${JSON.stringify(statement.contract)},
        ${statement.arity});

`,
    )
    .join("");
  const all = catalogue.statements
    .map((statement) => `\n        ${csharpMemberName(statement.name)},`)
    .join("");
  return `// <auto-generated>
// Code generated by scripts/generate-sql-catalogues.ts; DO NOT EDIT.
// </auto-generated>
#nullable enable

namespace ${catalogue.namespace};

/// <summary>
/// ${catalogue.summary}
/// Each statement keeps its native <c>$n</c> placeholders.
/// </summary>
internal static class ${catalogue.className}
{
${constantLines}    /// <summary>One catalogue statement.</summary>
    /// <param name="Name">The manifest name of the statement.</param>
    /// <param name="Sql">The SQL with native <c>$n</c> placeholders.</param>
    /// <param name="Arity">The number of distinct parameters, <c>$1</c> to <c>$Arity</c>.</param>
    internal sealed record Statement(string Name, string Sql, int Arity);

${entries}    /// <summary>Every statement, in manifest order.</summary>
    internal static readonly IReadOnlyList<Statement> All =
    [${all}${all === "" ? "" : "\n    "}];
}
`;
}

/**
 * The places where a shipped .NET project writes SQL by hand, as `<path>:<line>` relative to
 * `repository`. An Npgsql command whose SQL starts with a string literal is SQL written in place.
 * The scan reads `dotnet/src`, skips build output and generated `.g.cs` files, and sorts the result.
 * The test projects in `dotnet/tests` can write SQL, as the JVM tests do.
 */
export async function findInlineCSharpSql(repository: string): Promise<string[]> {
  const literal = String.raw`\s*(?:\$|@)*"`;
  const call = new RegExp(
    String.raw`(?:\bnew\s+Npgsql(?:Batch)?Command\(${literal}|\bCommandText\s*=${literal}|\.CreateCommand\(${literal})`,
    "g",
  );
  const violations: string[] = [];

  async function inspect(directory: string): Promise<void> {
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return;
      throw error;
    }
    for (const entry of entries) {
      const filename = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== "bin" && entry.name !== "obj") await inspect(filename);
        continue;
      }
      if (!entry.name.endsWith(".cs") || entry.name.endsWith(".g.cs")) continue;
      const source = await readFile(filename, "utf8");
      const relative = path.relative(repository, filename).split(path.sep).join("/");
      for (const match of source.matchAll(call)) {
        const line = source.slice(0, match.index).split("\n").length;
        violations.push(`${relative}:${line}`);
      }
    }
  }

  await inspect(path.join(repository, "dotnet/src"));
  return violations.toSorted();
}

using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Text.Json;
using Workhorse.ApiSnapshot;

// Writes api/dotnet.txt (ADR 0107, "Governed surface and release").
//
//   Workhorse.ApiSnapshot <output> <package>...
//
// scripts/generate-dotnet-api.ts passes each project directory under dotnet/src as a package. The
// build of this project puts each package assembly next to the tool, so a package without a
// ProjectReference here fails instead of leaving its section out.

const string ConfigurationPackage = "Workhorse.Hosting";
const string ConfigurationResource = "Workhorse.Hosting.ConfigurationKeys.json";

if (args.Length < 2)
{
    Console.Error.WriteLine("usage: Workhorse.ApiSnapshot <output> <package>...");
    return 2;
}

var packages = args[1..].Order(StringComparer.Ordinal).ToList();
var readers = new List<(string Package, PEReader File, MetadataReader Metadata)>();
foreach (var package in packages)
{
    var path = Path.Combine(AppContext.BaseDirectory, package + ".dll");
    if (!File.Exists(path))
    {
        Console.Error.WriteLine(
            $"{path} does not exist. Add a ProjectReference to dotnet/src/{package} in Workhorse.ApiSnapshot.csproj.");
        return 1;
    }
    var file = new PEReader(File.OpenRead(path));
    var metadata = file.GetMetadataReader();
    var assemblyName = metadata.GetString(metadata.GetAssemblyDefinition().Name);
    if (assemblyName != package)
    {
        Console.Error.WriteLine($"{path} holds the assembly {assemblyName}, not {package}. ADR 0107 makes each assembly name its package ID.");
        return 1;
    }
    readers.Add((package, file, metadata));
}

var enums = new EnumNames();
foreach (var (_, _, metadata) in readers)
{
    AssemblyApi.CollectEnums(metadata, enums);
}

var output = new StringBuilder();
output.Append("""
    # Public C# API
    #
    # Generated by `pnpm dotnet-api:generate` from the built assemblies of the Workhorse,
    # Workhorse.Hosting, Workhorse.EntityFrameworkCore, and Workhorse.AspNetCore packages. ADR 0054
    # and ADR 0107 govern this surface: a removed or renamed public type, member, or `Workhorse:*`
    # configuration key and a narrowed signature are breaking, and an addition is not.
    #
    # Each package section lists every public and protected type and member of the package. A member
    # line starts with the name of the type that declares it, and an `implements` line names one
    # interface of that type. Types are fully qualified, except the C# keyword types. A `?` marks a
    # nullable type. Parameter names are present, because a C# caller can pass an argument by name.
    # A record line implies the members that the compiler writes for every record: its equality
    # members, ToString, and the clone method behind `with`. A visible copy constructor has a line.

    """);

foreach (var (package, _, metadata) in readers)
{
    var api = new AssemblyApi(metadata, enums);
    output.Append('\n').Append("package ").Append(package).Append('\n');
    foreach (var block in api.Types())
    {
        var owner = packages
            .Where(candidate => block.Namespace == candidate || block.Namespace.StartsWith(candidate + ".", StringComparison.Ordinal))
            .MaxBy(candidate => candidate.Length);
        if (owner != package)
        {
            Console.Error.WriteLine(
                $"{block.Name} is in package {package} but in namespace {block.Namespace}. ADR 0107 puts each public type in the namespace of its package.");
            return 1;
        }
        output.Append('\n').Append(block.Header).Append('\n');
        foreach (var member in block.Members)
        {
            output.Append(member).Append('\n');
        }
    }
}

var hosting = readers.Single(reader => reader.Package == ConfigurationPackage);
output.Append('\n').Append("configuration of ").Append(ConfigurationPackage).Append('\n');
using (var keys = JsonDocument.Parse(Resource(hosting.File, hosting.Metadata, ConfigurationResource)))
{
    var lines = new List<string>();
    foreach (var key in keys.RootElement.GetProperty("keys").EnumerateArray())
    {
        var value = JsonSerializer.Serialize(key.GetProperty("default"));
        lines.Add($"key {key.GetProperty("key").GetString()}: {key.GetProperty("type").GetString()} = {value}");
    }
    lines.Sort(string.CompareOrdinal);
    foreach (var line in lines)
    {
        output.Append(line).Append('\n');
    }
}

File.WriteAllText(args[0], output.ToString());
foreach (var (_, file, _) in readers)
{
    file.Dispose();
}
return 0;

// The bytes of a resource that the assembly embeds.
static byte[] Resource(PEReader file, MetadataReader metadata, string name)
{
    foreach (var handle in metadata.ManifestResources)
    {
        var resource = metadata.GetManifestResource(handle);
        if (metadata.GetString(resource.Name) != name || !resource.Implementation.IsNil)
        {
            continue;
        }
        var directory = file.PEHeaders.CorHeader!.ResourcesDirectory;
        var section = file.GetSectionData(directory.RelativeVirtualAddress).GetReader();
        section.Offset = (int)resource.Offset;
        var length = section.ReadInt32();
        return section.ReadBytes(length);
    }
    throw new InvalidOperationException($"The assembly embeds no resource {name}.");
}
